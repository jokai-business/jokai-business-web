test('opportunity API rejects foreign relationships, stale writes and invalid values',async({browser,request})=>{
 const options={baseURL:process.env.BASE_URL||'https://localhost:8443',ignoreHTTPSErrors:!process.env.BASE_URL||process.env.E2E_ALLOW_SELF_SIGNED==='true'};
 const a=await browser.newPage(options),b=await browser.newPage(options);
 try{
 const sales=await login(a,'sales@example.test'),other=await login(b,'other@example.test');const marker=`Deal ${randomUUID()}`;
 const customer=(await (await request.post('/api/v1/customers',{headers:sales,data:{name:marker}})).json()).data;
 const foreign=(await (await request.post('/api/v1/customers',{headers:other,data:{name:marker}})).json()).data;
 const stages=(await (await request.get('/api/v1/pipeline-stages',{headers:sales})).json()).data;
 const foreignStages=(await (await request.get('/api/v1/pipeline-stages',{headers:other})).json()).data;
 const otherMe=(await (await request.get('/api/v1/me',{headers:other})).json()).data;
 expect((await request.put(`/api/v1/pipeline-stages/${stages[0].id}`,{headers:other,data:{name:'Intrusion',position:10,isClosed:false,isWon:false,version:1}})).status()).toBe(404);
 const body={customerId:customer.id,title:marker,stageId:stages[0].id,probability:30,expectedValue:'9.99',expectedCloseDate:'2026-12-01'};
 const created=await request.post('/api/v1/opportunities',{headers:sales,data:body});expect(created.status()).toBe(201);const deal=(await created.json()).data;
 for(const suffix of ['', '/activities'])expect((await request.get(`/api/v1/opportunities/${deal.id}${suffix}`,{headers:other})).status()).toBe(404);
 expect((await request.patch(`/api/v1/opportunities/${deal.id}`,{headers:other,data:{version:1,title:'Intrusion'}})).status()).toBe(404);
 expect((await request.post(`/api/v1/opportunities/${deal.id}/activities`,{headers:other,data:{body:'Intrusion'}})).status()).toBe(404);
 expect((await (await request.get('/api/v1/opportunities',{headers:other,params:{q:marker}})).json()).meta.total).toBe(0);
 for(const extra of [{customerId:foreign.id},{stageId:foreignStages[0].id},{ownerId:otherMe.user.id},{organization_id:otherMe.organization.id},{expectedValue:'1.001'},{expectedValue:'-1'},{probability:101},{expectedCloseDate:'2026-02-30'}])expect((await request.post('/api/v1/opportunities',{headers:sales,data:{...body,...extra}})).status()).toBe(400);
 expect((await request.post('/api/v1/pipeline-stages',{headers:sales,data:{name:'Forbidden',position:1,isClosed:false,isWon:false,version:0}})).status()).toBe(403);
 expect((await request.patch(`/api/v1/opportunities/${deal.id}`,{headers:sales,data:{version:1,customerId:foreign.id}})).status()).toBe(400);
 const patch=await request.patch(`/api/v1/opportunities/${deal.id}`,{headers:sales,data:{version:1,nextAction:'Call',expectedCloseDate:''}});expect(patch.status()).toBe(200);expect((await patch.json()).data.expectedValue).toBe('9.99');
 expect((await request.patch(`/api/v1/opportunities/${deal.id}`,{headers:sales,data:{version:1,title:'Stale'}})).status()).toBe(409);
 expect((await request.get('/api/v1/opportunities',{headers:sales,params:{pageSize:101}})).status()).toBe(400);
 expect((await request.get(`/api/v1/opportunities/${deal.id}/activities`,{headers:sales,params:{page:0}})).status()).toBe(400);
 await request.post('/api/v1/opportunities',{headers:sales,data:body});
 const first=(await (await request.get('/api/v1/opportunities',{headers:sales,params:{q:marker,pageSize:1}})).json());const second=(await (await request.get('/api/v1/opportunities',{headers:sales,params:{q:marker,pageSize:1,page:2}})).json());
 expect(first.meta.total).toBe(2);expect(second.meta.total).toBe(2);expect(first.data[0].id).not.toBe(second.data[0].id);
 const beyond=await (await request.get('/api/v1/opportunities',{headers:sales,params:{q:marker,page:10}})).json();expect(beyond.meta.total).toBe(2);expect(beyond.data).toHaveLength(0);
 }finally{await a.close();await b.close();}
});

test('administrator configures a pipeline stage and stale stage edits are rejected',async({page,request})=>{
 const headers=await login(page,'admin@example.test');const name=`Review ${randomUUID().slice(0,8)}`;
 await page.getByRole('button',{name:'Opportunities',exact:true}).click();
 await page.getByRole('button',{name:'Pipeline settings',exact:true}).click();
 await page.getByRole('button',{name:'Add stage',exact:true}).click();
 await page.getByLabel('Stage name',{exact:true}).fill(name);
 await page.getByLabel('Position',{exact:true}).fill('25');
 await page.getByRole('button',{name:'Save stage',exact:true}).click();
 await expect(page.getByText('Pipeline stage saved.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:`Edit stage ${name}`,exact:true}).click();
 await page.getByLabel('Stage name',{exact:true}).fill(name+' revised');
 await page.getByRole('button',{name:'Save stage',exact:true}).click();
 await expect(page.getByRole('button',{name:`Edit stage ${name} revised`,exact:true})).toBeVisible();
 const stages=(await (await request.get('/api/v1/pipeline-stages',{headers})).json()).data;
 const stage=stages.find((s:{name:string})=>s.name===name+' revised');
 const body={name:stage.name,position:stage.position,isClosed:false,isWon:false,version:1};
 expect((await request.put(`/api/v1/pipeline-stages/${stage.id}`,{headers,data:body})).status()).toBe(409);
 expect((await request.post('/api/v1/pipeline-stages',{headers,data:{...body,version:0}})).status()).toBe(400);
 expect((await request.put(`/api/v1/pipeline-stages/${stage.id}`,{headers,data:{...body,version:stage.version,isWon:true}})).status()).toBe(400);
 await page.getByRole('button',{name:'Close settings',exact:true}).click();
 await expect(page.getByLabel('Filter by stage').locator('option',{hasText:name+' revised'})).toBeAttached();
});
