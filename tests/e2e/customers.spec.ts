import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { login } from './helpers';
test('sales user creates, searches, edits a customer and adds contacts with activity', async ({ page, request }) => {
 const headers=await login(page,'sales@example.test');const name=`Customer ${randomUUID()}`;
 await page.getByRole('button',{name:'Customers',exact:true}).click();
 await expect(page).toHaveURL(/\/customers$/);
 await page.getByRole('button',{name:'New customer',exact:true}).click();
 await page.getByLabel('Customer name',{exact:true}).fill(name);
 await page.getByLabel('Email',{exact:true}).fill('contact@example.test');
 await page.getByLabel('Industry',{exact:true}).fill('Consulting');
 await page.getByLabel('Country',{exact:true}).fill('Cambodia');
 await page.getByLabel('Notes',{exact:true}).fill('Initial introduction');
 await page.getByRole('button',{name:'Save customer',exact:true}).click();
 await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
 const id=page.url().split('/').at(-1)!;
 await page.getByRole('button',{name:'Edit customer',exact:true}).click();
 await page.getByLabel('Status',{exact:true}).selectOption('active');
 await page.getByLabel('Notes',{exact:true}).fill('Follow up next week');
 await page.getByRole('button',{name:'Save customer',exact:true}).click();
 await expect(page.getByText('Customer saved.',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'contacts',exact:true}).click();
 await page.getByLabel('Contact name',{exact:true}).fill('Jane Customer');
 await page.getByLabel('Contact email',{exact:true}).fill('jane@example.test');
 await page.getByLabel('Job title',{exact:true}).fill('Operations manager');
 await page.getByRole('button',{name:'Add contact',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Jane Customer',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'activity',exact:true}).click();
 await expect(page.getByText('Customer created',{exact:true})).toBeVisible();
 await expect(page.getByText('Customer updated',{exact:true})).toBeVisible();
 await expect(page.getByText('Contact added',{exact:true})).toBeVisible();
 await page.getByRole('link',{name:'← All customers',exact:true}).click();
 await page.getByLabel('Search customers',{exact:true}).fill(name);
 await page.getByRole('button',{name:'Search',exact:true}).click();
 await expect(page.getByRole('link',{name,exact:true})).toBeVisible();
 const current=await (await request.get(`/api/v1/customers/${id}`,{headers})).json();
 expect(current.data.status).toBe('active');expect(current.data.notes).toBe('Follow up next week');
 expect(current.data.email).toBe('contact@example.test');
 expect((await request.patch(`/api/v1/customers/${id}`,{headers,data:{version:1,name:'Stale'}})).status()).toBe(409);
});
test('customer API enforces tenant isolation, owner scope, input validation and pagination', async ({ browser, request }) => {
 const a=await browser.newPage({baseURL:process.env.BASE_URL||'https://localhost:8443',ignoreHTTPSErrors:!process.env.BASE_URL||process.env.E2E_ALLOW_SELF_SIGNED==='true'});const b=await browser.newPage({baseURL:process.env.BASE_URL||'https://localhost:8443',ignoreHTTPSErrors:!process.env.BASE_URL||process.env.E2E_ALLOW_SELF_SIGNED==='true'});
 try {
 const sales=await login(a,'sales@example.test');const other=await login(b,'other@example.test');
 const otherMe=await (await request.get('/api/v1/me',{headers:other})).json();
 const marker=`Isolation-${randomUUID()}`;
 const created=await request.post('/api/v1/customers',{headers:sales,data:{name:marker}});expect(created.status()).toBe(201);
 const customer=(await created.json()).data;
 for(const path of [`/api/v1/customers/${customer.id}`,`/api/v1/customers/${customer.id}/contacts`,`/api/v1/customers/${customer.id}/activity`])expect((await request.get(path,{headers:other})).status()).toBe(404);
 expect((await request.patch(`/api/v1/customers/${customer.id}`,{headers:other,data:{version:1,name:'Intrusion'}})).status()).toBe(404);
 expect((await request.post(`/api/v1/customers/${customer.id}/contacts`,{headers:other,data:{name:'Intrusion'}})).status()).toBe(404);
 const hidden=await (await request.get('/api/v1/customers',{headers:other,params:{q:marker}})).json();expect(hidden.meta.total).toBe(0);
 expect((await request.post('/api/v1/customers',{headers:sales,data:{name:marker,ownerId:otherMe.data.user.id}})).status()).toBe(400);
 expect((await request.post('/api/v1/customers',{headers:sales,data:{name:marker,organization_id:otherMe.data.organization.id}})).status()).toBe(400);
 expect((await request.post('/api/v1/customers',{headers:sales,data:{name:'Bad',website:'javascript:alert(1)'}})).status()).toBe(400);
 expect((await request.get('/api/v1/customers',{headers:sales,params:{pageSize:101}})).status()).toBe(400);
 const second=await request.post('/api/v1/customers',{headers:sales,data:{name:marker+' second'}});expect(second.status()).toBe(201);
 const one=await (await request.get('/api/v1/customers',{headers:sales,params:{q:marker,pageSize:1,page:1}})).json();
 const two=await (await request.get('/api/v1/customers',{headers:sales,params:{q:marker,pageSize:1,page:2}})).json();
 expect(one.meta.total).toBe(2);expect(two.meta.total).toBe(2);expect(one.data).toHaveLength(1);expect(two.data).toHaveLength(1);expect(one.data[0].id).not.toBe(two.data[0].id);
 }finally{await a.close();await b.close();}
});
