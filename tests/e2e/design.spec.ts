import {test,expect} from '@playwright/test';
import {login} from './helpers';
test('workspace supports collapsed navigation, width controls and customer card view',async({page})=>{
 await login(page,'admin@example.test');
 await page.getByRole('button',{name:'Customers',exact:true}).click();
 await page.getByRole('button',{name:'Collapse navigation',exact:true}).click();
 await expect(page.getByRole('button',{name:'Expand navigation',exact:true})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Customers',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Overview',exact:true}).click();
 await page.getByRole('button',{name:'Customers',exact:true}).click();
 await expect(page.getByRole('button',{name:'Expand navigation',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Use full width',exact:true}).click();
 await expect(page.getByRole('button',{name:'Use centered layout',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByRole('button',{name:'Card view',exact:true}).click();
 await expect(page.getByRole('button',{name:'Card view',exact:true})).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('.customer-table-wrap')).not.toBeVisible();
 await page.getByRole('button',{name:'Table view',exact:true}).click();
 await expect(page.locator('.customer-table-wrap')).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
test('mobile navigation traps focus, closes with Escape, and customer forms fit',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await login(page,'sales@example.test');
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await page.keyboard.press('Escape');
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.getByRole('button',{name:'Open navigation',exact:true})).toBeFocused();
 await page.getByRole('button',{name:'Open navigation',exact:true}).click();
 await page.getByRole('button',{name:'Customers',exact:true}).click();
 await expect(page.getByRole('dialog')).not.toBeVisible();
 await expect(page.getByRole('heading',{name:'Customers',exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'New customer',exact:true}).click();
 await expect(page.getByLabel('Customer name',{exact:true})).toBeFocused();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Customers',exact:true})).toBeInViewport();
});
